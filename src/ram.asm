        INCLUDE "zos_sys.asm"
        EXTERN __tail
        PUBLIC WORKSPACE_BASE, WORKSPACE_END
        PUBLIC D_ORIGINAL_FONT, G_SPANS, D_PARAMS, D_GLYPH, D_CURSOR
        PUBLIC FILE_CHANNELS, OPTVAL, KEY_QUEUE, KEY_EVENTS, ZOS_BUFFER

; The flat executable contains code and initialized state only. Reserve RAM
; by placing PAGE above this runtime workspace; no DEFS bytes enter the file.
DEFC WORKSPACE_BASE = (__tail + 255) & 0xff00
DEFC ACCS = WORKSPACE_BASE
DEFC BUFFER = ACCS + 256
DEFC STAVAR = BUFFER + 256
DEFC DYNVAR = STAVAR + 27*4
DEFC FNPTR = DYNVAR + 54*2
DEFC PROPTR = FNPTR + 2
DEFC PAGE = PROPTR + 2
DEFC TOP = PAGE + 2
DEFC LOMEM = TOP + 2
DEFC FREE = LOMEM + 2
DEFC HIMEM = FREE + 2
DEFC LINENO = HIMEM + 2
DEFC TRACEN = LINENO + 2
DEFC AUTONO = TRACEN + 2
DEFC ERRTRP = AUTONO + 2
DEFC ERRTXT = ERRTRP + 2
DEFC DATPTR = ERRTXT + 2
DEFC ERL = DATPTR + 2
DEFC ERRLIN = ERL + 2
DEFC RANDOM = ERRLIN + 2
DEFC COUNT = RANDOM + 5
DEFC WIDTH = COUNT + 1
DEFC ERR = WIDTH + 1
DEFC LISTON = ERR + 1
DEFC INCREM = LISTON + 1
DEFC OC = STAVAR + 15*4
DEFC PC = STAVAR + 16*4
; Keep the interpreter's three page-aligned buffers together. The cold-start
; purge initializes the variable page before the OS adapter uses it.
DEFC DISPLAY_WORKSPACE = (INCREM + 1 + 255) & 0xff00
DEFC D_ORIGINAL_FONT = DISPLAY_WORKSPACE
DEFC G_SPANS = D_ORIGINAL_FONT + 3072
DEFC D_PARAMS = G_SPANS + 800
DEFC D_GLYPH = D_PARAMS + 9
DEFC D_CURSOR = D_GLYPH + 12
DEFC FILE_CHANNELS = D_CURSOR + 2
DEFC OPTVAL = FILE_CHANNELS + 128
DEFC KEY_QUEUE = OPTVAL + 1
DEFC KEY_EVENTS = KEY_QUEUE + 16
DEFC ZOS_BUFFER = KEY_EVENTS + 64
DEFC WORKSPACE_END = ZOS_BUFFER + ZOS_STAT_SIZE
DEFC USER = (WORKSPACE_END + 255) & 0xff00
